/**
 * Brief 2-1, step one — the tenant column, generated.
 *
 * Reads prisma/schema.prisma, adds `tenantId` (nullable, defaulting to the
 * Alto HR tenant at the database) and an index to every model that should
 * carry one, and writes the matching migration SQL. Additive only: no
 * NOT NULL, no foreign key, no policy. Those are later steps.
 *
 *   cd apps/api && npx tsx scripts/gen-tenant-columns.ts [--migration <folder name>]
 *
 * Idempotent: a model that already has tenantId is left alone, and the SQL
 * uses IF NOT EXISTS throughout, so re-running after new models are added
 * emits only what is missing.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** The one employer today. Fixed so every environment agrees. */
export const ALTO_TENANT_ID = '00000000-0000-4000-8000-000000000001';

/** No tenant column at all: the tenant table itself and shared reference data (decision 4). */
const EXEMPT = new Set(['Tenant', 'PayrollConfig', 'LocalTaxRule', 'GeoCache']);
/** Nullable with no default: platform-wide telemetry (decision 7). */
const NO_DEFAULT = new Set(['ApiBoot', 'RouteUsageDaily', 'WebVitalDaily', 'ReliabilityWeek']);

const DEFAULT_ATTR = `@default(dbgenerated("'${ALTO_TENANT_ID}'::uuid"))`;

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

export function patchSchema(schema: string): { schema: string; tables: { model: string; table: string; defaulted: boolean }[]; skipped: string[] } {
  const tables: { model: string; table: string; defaulted: boolean }[] = [];
  const skipped: string[] = [];
  const out = schema.replace(/^model (\w+) \{\n([\s\S]*?)^\}/gm, (whole, name: string, body: string) => {
    if (EXEMPT.has(name)) return whole;
    const mapMatch = body.match(/@@map\("([^"]+)"\)/);
    const table = mapMatch ? mapMatch[1]! : name;
    const defaulted = !NO_DEFAULT.has(name);
    tables.push({ model: name, table, defaulted });
    if (/^\s+tenantId\s/m.test(body)) {
      skipped.push(name);
      return whole;
    }
    const lines = body.split('\n');
    // The column goes after the last scalar field, before relations and @@ lines.
    let insertAt = lines.length;
    for (let i = 0; i < lines.length; i++) {
      const l = lines[i]!;
      if (/^\s+@@/.test(l) || /^\s+\w+\s+\w+(\[\]|\?)?\s+@relation/.test(l) || /^\s+\w+\s+[A-Z]\w+(\[\]|\?)?\s*$/.test(l) || /^\s+\w+\s+[A-Z]\w+(\[\]|\?)?\s+@relation/.test(l)) {
        insertAt = i;
        break;
      }
    }
    const field = `  /// Brief 2-1: the tenant this row belongs to. Nullable and defaulted until the enforcing migration.\n  tenantId ${defaulted ? `String? @db.Uuid ${DEFAULT_ATTR}` : 'String? @db.Uuid'}`;
    lines.splice(insertAt, 0, field);
    // Index before the closing brace, after any existing @@ lines.
    let last = lines.length - 1;
    while (last >= 0 && lines[last]!.trim() === '') last--;
    lines.splice(last + 1, 0, '  @@index([tenantId])');
    return `model ${name} {\n${lines.join('\n')}\n}`;
  });
  return { schema: out, tables, skipped };
}

export function migrationSql(tables: { table: string; defaulted: boolean }[]): string {
  const lines: string[] = [
    '-- Brief 2-1, step one — Tenant and the tenant column, additive only.',
    '--',
    '-- Generated by scripts/gen-tenant-columns.ts. Every tenant-scoped table',
    '-- gains a nullable "tenantId" that defaults, at the database, to the Alto',
    '-- HR tenant: existing rows read as Alto HR without a rewrite (Postgres',
    "-- stores a constant default in the catalog), and every new row is Alto HR's",
    '-- until the application sets it. No NOT NULL, no foreign key, no policy',
    '-- yet; those are the enforcing steps after the observe period.',
    '',
    `CREATE TYPE "TenantStatus" AS ENUM ('ACTIVE', 'SUSPENDED');`,
    '',
    'CREATE TABLE IF NOT EXISTS "Tenant" (',
    '  "id"        UUID NOT NULL DEFAULT gen_random_uuid(),',
    '  "slug"      VARCHAR(60) NOT NULL,',
    '  "name"      VARCHAR(160) NOT NULL,',
    `  "plan"      VARCHAR(40) NOT NULL DEFAULT 'internal',`,
    `  "status"    "TenantStatus" NOT NULL DEFAULT 'ACTIVE',`,
    `  "features"  JSONB NOT NULL DEFAULT '{}'::jsonb,`,
    '  "createdAt" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,',
    '  "updatedAt" TIMESTAMPTZ(6) NOT NULL,',
    '  CONSTRAINT "Tenant_pkey" PRIMARY KEY ("id")',
    ');',
    'CREATE UNIQUE INDEX IF NOT EXISTS "Tenant_slug_key" ON "Tenant"("slug");',
    '',
    '-- Alto HR is tenant 1.',
    `INSERT INTO "Tenant" ("id", "slug", "name", "plan", "status", "updatedAt")`,
    `VALUES ('${ALTO_TENANT_ID}', 'alto-hr', 'Alto HR', 'internal', 'ACTIVE', CURRENT_TIMESTAMP)`,
    'ON CONFLICT ("id") DO NOTHING;',
    '',
  ];
  for (const t of tables) {
    lines.push(`ALTER TABLE "${t.table}" ADD COLUMN IF NOT EXISTS "tenantId" UUID${t.defaulted ? ` DEFAULT '${ALTO_TENANT_ID}'` : ''};`);
    lines.push(`CREATE INDEX IF NOT EXISTS "${t.table}_tenantId_idx" ON "${t.table}"("tenantId");`);
  }
  lines.push('');
  return lines.join('\n');
}

const TENANT_MODEL = `
// ===== Brief 2-1 — Tenants ==================================================
//
// One customer organization. Every tenant-scoped table carries a nullable
// tenantId defaulting to Alto HR (tenant 1) until the enforcing migration
// makes it required and the database policy reads it. Reference data
// (PayrollConfig, LocalTaxRule, GeoCache) stays global; platform telemetry
// carries a null tenant.

enum TenantStatus {
  ACTIVE
  SUSPENDED
}

model Tenant {
  id        String       @id @default(dbgenerated("gen_random_uuid()")) @db.Uuid
  slug      String       @unique @db.VarChar(60)
  name      String       @db.VarChar(160)
  plan      String       @default("internal") @db.VarChar(40)
  status    TenantStatus @default(ACTIVE)
  /// Feature flags per tenant, read by the application.
  features  Json         @default("{}")
  createdAt DateTime     @default(now()) @db.Timestamptz(6)
  updatedAt DateTime     @updatedAt @db.Timestamptz(6)
}
`;

function main() {
  const root = join(process.cwd(), 'prisma');
  const schemaPath = join(root, 'schema.prisma');
  let schema = readFileSync(schemaPath, 'utf8');
  if (!/^model Tenant \{/m.test(schema)) schema += TENANT_MODEL;
  const { schema: patched, tables, skipped } = patchSchema(schema);
  writeFileSync(schemaPath, patched);
  const folder = arg('--migration');
  if (folder) {
    const dir = join(root, 'migrations', folder);
    if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'migration.sql'), migrationSql(tables));
    console.log(`wrote ${dir}/migration.sql`);
  }
  console.log(`tenant column on ${tables.length} models (${skipped.length} already had it); exempt: ${[...EXEMPT].join(', ')}`);
}

const invokedDirectly = process.argv[1] && /gen-tenant-columns\.ts$/.test(process.argv[1]);
if (invokedDirectly) main();
